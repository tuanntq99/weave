const REGISTRY: ReadonlyMap<string, { icon: LucideIcon; words: string }> = new Map(
  ICONS.map(([key, icon, words]) => [key, { icon, words: `${key.replaceAll("-", " ")} ${words}` }]),
);

/** Every mark a column can take, by key, in the picker's order. */
export const PROPERTY_ICON_KEYS: readonly string[] = ICONS.map(([key]) => key);

/** The mark a stored key names, or undefined for a key this build does not
 *  know — the column then wears its type's. */
export function propertyIcon(key: unknown): LucideIcon | undefined {
  return typeof key === "string" ? REGISTRY.get(key)?.icon : undefined;
}

/** The keys whose names or words contain every word of `query`. */
export function findPropertyIcons(query: string): string[] {
  const wanted = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  if (!wanted.length) return [...PROPERTY_ICON_KEYS];
  return PROPERTY_ICON_KEYS.filter((key) => {
    const words = REGISTRY.get(key)!.words;
    return wanted.every((word) => words.includes(word));
  });
}
